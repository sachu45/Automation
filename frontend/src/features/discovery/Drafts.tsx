import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { CheckCircle2, ExternalLink, RefreshCw } from "lucide-react";
import { useEffect, useState } from "react";
import { Link } from "react-router-dom";
import { toast } from "sonner";
import { Alert, Badge, Button, Card, CardBody, CardHeader, EmptyState, ErrorState, Field, Input, Select, Spinner, Textarea } from "@/components/ui";
import { ConfirmDialog } from "@/components/ui/dialog";
import { safeHref } from "@/features/discovery/Signals";
import { api, errorMessage } from "@/lib/api";
import { fmtDate, titleCase } from "@/lib/utils";
import type { DiscoveryDraft } from "@/types/api";

export function DiscoveryDrafts() {
  const [status, setStatus] = useState("draft");
  const drafts = useQuery({ queryKey: ["discovery", "drafts", status], queryFn: () => api.get<DiscoveryDraft[]>("/api/discovery/drafts", { status }) });
  return (
    <div className="space-y-4">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <p className="max-w-2xl text-sm text-muted">
          Drafts written from discovered signals. Check every claim against the evidence, edit, then approve. Approval doesn't send anything — send an approved draft from the lead's page
          (Send email), which shows the final rendered message and still respects suppression, dry-run and limits.
        </p>
        <Select aria-label="Draft status" className="w-auto" value={status} onChange={(e) => setStatus(e.target.value)}>
          <option value="draft">Awaiting review</option>
          <option value="approved">Approved</option>
          <option value="">All</option>
        </Select>
      </div>
      {drafts.isLoading ? (
        <Spinner />
      ) : drafts.isError ? (
        <ErrorState error={drafts.error} onRetry={() => drafts.refetch()} />
      ) : !drafts.data?.length ? (
        <Card>
          <EmptyState title="No drafts here" description="Qualified signals with a verified contact email produce drafts automatically (unless drafting is turned off in Rules)." />
        </Card>
      ) : (
        drafts.data.map((d) => <DraftCard key={d.id} draft={d} />)
      )}
    </div>
  );
}

function DraftCard({ draft }: { draft: DiscoveryDraft }) {
  const qc = useQueryClient();
  const [subject, setSubject] = useState(draft.subject);
  const [body, setBody] = useState(draft.body);
  const [confirm, setConfirm] = useState(false);
  useEffect(() => {
    setSubject(draft.subject);
    setBody(draft.body);
  }, [draft.subject, draft.body]);
  const dirty = subject !== draft.subject || body !== draft.body;
  const invalidate = () => qc.invalidateQueries({ queryKey: ["discovery"] });
  const save = useMutation({
    mutationFn: () => api.patch(`/api/ai/drafts/${draft.id}`, { subject, body }),
    onSuccess: () => {
      toast.success("Draft saved (any previous approval is cleared)");
      invalidate();
    },
    onError: (e) => toast.error(errorMessage(e)),
  });
  const approve = useMutation({
    mutationFn: async () => {
      if (dirty) await api.patch(`/api/ai/drafts/${draft.id}`, { subject, body });
      return api.post(`/api/ai/drafts/${draft.id}/approve`);
    },
    onSuccess: () => {
      toast.success("Approved. Send it from the lead's page when you're ready.");
      setConfirm(false);
      invalidate();
    },
    onError: (e) => toast.error(errorMessage(e)),
  });
  const regenerate = useMutation({
    mutationFn: () => api.post(`/api/discovery/signals/${draft.signal?.id}/reprocess`),
    onSuccess: () => {
      toast.success("A new version will be generated by the worker");
      invalidate();
    },
    onError: (e) => toast.error(errorMessage(e)),
  });
  const s = draft.signal;
  return (
    <Card>
      <CardHeader
        title={
          <span className="flex flex-wrap items-center gap-2">
            Draft #{draft.id} {draft.label && <Badge>{draft.label}</Badge>}
            {draft.status === "approved" ? <Badge tone="ok">approved</Badge> : <Badge tone="warn">needs approval</Badge>}
            {draft.test_mode && <Badge tone="info">test mode</Badge>}
          </span>
        }
        description={`${draft.provider} · ${fmtDate(draft.created_at)}`}
        actions={
          <>
            {s && (
              <Button size="sm" onClick={() => regenerate.mutate()} loading={regenerate.isPending}>
                <RefreshCw className="h-3.5 w-3.5" /> Regenerate
              </Button>
            )}
            <Button size="sm" onClick={() => save.mutate()} disabled={!dirty} loading={save.isPending}>
              Save changes
            </Button>
            {draft.status !== "approved" && (
              <Button size="sm" variant="primary" onClick={() => setConfirm(true)} disabled={!subject.trim() || !body.trim()}>
                <CheckCircle2 className="h-3.5 w-3.5" /> Approve…
              </Button>
            )}
            {draft.lead && (
              <Link to={`/leads/${draft.lead.id}`}>
                <Button size="sm" variant="ghost">Open lead</Button>
              </Link>
            )}
          </>
        }
      />
      <CardBody className="grid grid-cols-1 gap-5 lg:grid-cols-2">
        <div className="space-y-3">
          {draft.lead && (
            <p className="text-sm">
              To <b>{draft.lead.name ?? draft.lead.email}</b> &lt;{draft.lead.email}&gt;{draft.lead.company ? ` · ${draft.lead.company}` : ""}
            </p>
          )}
          {draft.warnings.length > 0 && (
            <Alert tone="warn" title="Check before approving">
              <ul className="list-disc pl-4">{draft.warnings.map((w) => <li key={w}>{w}</li>)}</ul>
            </Alert>
          )}
          <Field label="Subject" htmlFor={`ds-${draft.id}`}>
            <Input id={`ds-${draft.id}`} value={subject} onChange={(e) => setSubject(e.target.value)} />
          </Field>
          <Field label="Body" htmlFor={`db-${draft.id}`} hint="{{signature}} and the opt-out footer are filled in when the email is sent.">
            <Textarea id={`db-${draft.id}`} rows={11} value={body} onChange={(e) => setBody(e.target.value)} />
          </Field>
        </div>
        <div className="space-y-3 text-sm">
          <p className="text-xs font-medium uppercase tracking-wide text-muted">Source evidence</p>
          {s ? (
            <div className="rounded-lg border border-border bg-bg/40 p-3">
              <p className="font-medium">{s.title}</p>
              <p className="mt-1 text-xs text-muted">
                {s.source_provider} · {titleCase(s.category ?? "")} · published {fmtDate(s.published_at, false)} · score {s.relevance_score ?? "—"}
              </p>
              <p className="mt-2 whitespace-pre-wrap text-ink-2">{s.excerpt}</p>
              {safeHref(s.source_url) && (
                <a href={safeHref(s.source_url)} target="_blank" rel="noreferrer noopener" className="mt-2 inline-flex items-center gap-1 text-brand hover:underline">
                  Open original source <ExternalLink className="h-3.5 w-3.5" />
                </a>
              )}
            </div>
          ) : (
            <p className="text-muted">Signal no longer available.</p>
          )}
          {draft.evidence_refs.length > 1 && (
            <ul className="space-y-1 text-xs text-muted">
              {draft.evidence_refs.map((r, i) => (
                <li key={i}>
                  {r.kind} · {r.provider} · {fmtDate(r.retrieved_at)}{" "}
                  {safeHref(r.url) && <a className="text-brand hover:underline" href={safeHref(r.url)} target="_blank" rel="noreferrer noopener">open</a>}
                </li>
              ))}
            </ul>
          )}
        </div>
      </CardBody>
      <ConfirmDialog
        open={confirm}
        onOpenChange={setConfirm}
        title="Approve this exact text?"
        description="Approval marks the draft as reviewed. It does not send anything; editing it later clears the approval."
        confirmLabel="Approve draft"
        loading={approve.isPending}
        onConfirm={() => approve.mutate()}
      >
        <div className="rounded-lg border border-border p-3 text-sm">
          <p className="font-semibold">{subject}</p>
          <pre className="mt-2 max-h-64 overflow-auto whitespace-pre-wrap font-sans text-ink-2">{body}</pre>
        </div>
      </ConfirmDialog>
    </Card>
  );
}
